def norm(text):
    """Compares place names without case, accents and punctuation."""
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = text.lower().replace("ß", "ss")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return " ".join(text.split())


def fmt(value):
    return f"{value:.4f}"


def write(path, header, areas, prefixes):
    """Writes one data file. `areas` has (id, cc, kind, lat, lon, prefix,
    name) and `prefixes` has (digits, id)."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# TalkOps call origin data, format 1\n")
        for key in COMMENT_KEYS:
            if key in header:
                f.write(f"# {key}: {header[key]}\n")
        f.write("# generated by: tools/geo/generate.py (do not edit)\n")
        for a in areas:
            area_id, country, kind, lat, lon, prefix, name = a
            name = name.replace("\t", " ").strip()
            f.write(f"A\t{area_id}\t{country}\t{kind}\t{fmt(lat)}\t{fmt(lon)}\t{prefix}\t{name}\n")
        for digits, area_id in prefixes:
            f.write(f"P\t{digits}\t{area_id}\n")
    print(
        f"{os.path.relpath(path, ROOT)}: {len(areas)} areas, {len(prefixes)} prefixes, "
        f"{os.path.getsize(path)} bytes"
    )


def read_lpn(path):
    """Reads a libphonenumber prefix file (`prefix|text`)."""
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "|" not in line:
                continue
            prefix, text = line.split("|", 1)
            out.append((prefix, text.strip()))
    return out


class Places:
    """GeoNames places with a population, for name lookups."""

    def __init__(self, raw):
        self.by_country = defaultdict(lambda: defaultdict(list))
        self.admin1 = defaultdict(dict)
        self.biggest_in_admin1 = {}
        with open(os.path.join(raw, "cities15000.txt"), encoding="utf-8") as f:
            for row in csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
                (_, name, ascii_name, alternates, lat, lon, _, _, cc, _, a1) = row[:11]
                pop = int(row[14] or 0)
                place = (float(lat), float(lon), pop, a1)
                names = {norm(name), norm(ascii_name)}
                for n in names:
                    self.by_country[cc][n].append((0,) + place)
                for alt in alternates.split(","):
                    n = norm(alt)
                    if n and n not in names:
                        self.by_country[cc][n].append((1,) + place)
                key = (cc, a1)
                if key not in self.biggest_in_admin1 or self.biggest_in_admin1[key][2] < pop:
                    self.biggest_in_admin1[key] = place
        with open(os.path.join(raw, "admin1CodesASCII.txt"), encoding="utf-8") as f:
            for row in csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
                cc, a1 = row[0].split(".", 1)
                for n in (row[1], row[2]):
                    self.admin1[cc][norm(n)] = a1

    def find(self, cc, name, admin1=None):
        """Coordinates of the best match: exact names before alternate names,
        then the largest population."""
        candidates = self.by_country.get(cc, {}).get(norm(name), [])
        if admin1:
            candidates = [c for c in candidates if c[4] == admin1] or []
        if candidates:
            best = min(candidates, key=lambda c: (c[0], -c[3]))
            return best[1], best[2]
        a1 = self.admin1.get(cc, {}).get(norm(name))
        if a1 and (cc, a1) in self.biggest_in_admin1:
            p = self.biggest_in_admin1[(cc, a1)]
            return p[0], p[1]
        return None


def lpn_place_names(text):
    """Candidate names of a libphonenumber geocoding text, most specific
    first. Examples: `Jersey City, NJ`, `Bienne/Neuchâtel`, `Milan`."""
    yield text, None
    if ", " in text:
        head, tail = text.rsplit(", ", 1)
        yield head, tail
        yield head, None
    for part in re.split(r"[/;]| - ", text):
        if part.strip() and part.strip() != text:
            yield part.strip(), None
    if "(" in text:
        yield re.sub(r"\s*\(.*?\)", "", text), None


def merge_siblings(mapping_by_prefix, taken=frozenset()):
    """Replaces ten sibling prefixes (`…0` to `…9`) that map to the same area
    with their common parent prefix. The parent must be free or map to the
    same area. Repeats until nothing changes."""
    m = dict(mapping_by_prefix)
    changed = True
    while changed:
        changed = False
        groups = defaultdict(dict)
        for prefix, area in m.items():
            if len(prefix) > 1:
                groups[prefix[:-1]][prefix[-1]] = area
        for parent, children in groups.items():
            if len(children) != 10 or len(set(children.values())) != 1:
                continue
            area = next(iter(children.values()))
            if m.get(parent, area) != area or parent in taken:
                continue
            for digit in children:
                del m[parent + digit]
            m[parent] = area
            changed = True
    return m


def compact(mapping_by_prefix, taken=frozenset()):
    """Leaves out prefixes whose nearest shorter prefix maps to the same area.
    `taken` has prefixes of other files that a merge must not create."""
    mapping_by_prefix = merge_siblings(mapping_by_prefix, taken)
    keep = {}
    for prefix in sorted(mapping_by_prefix, key=len):
        area = mapping_by_prefix[prefix]
        parent = None
        for n in range(len(prefix) - 1, 0, -1):
            if prefix[:n] in keep:
                parent = keep[prefix[:n]]
                break
        if parent != area:
            keep[prefix] = area
    return keep


def common_prefix(values):
    first, last = min(values), max(values)
    n = 0
    while n < min(len(first), len(last)) and first[n] == last[n]:
        n += 1
    return first[:n]


def display(cc, digits):
    rest = digits[len(cc) :]
    return f"{cc} {rest}" if rest else cc


class Regions:
    """ISO regions by calling code prefix (countryInfo.txt)."""

    def __init__(self, raw):
        self.names = {}
        self.capitals = {}
        self.prefix_to_region = {}
        self.region_prefix = {}
        first_code = {}
        with open(os.path.join(raw, "countryInfo.txt"), encoding="utf-8") as f:
            for line in f:
                if line.startswith("#"):
                    continue
                row = line.rstrip("\n").split("\t")
                iso, name, capital, phone = row[0], row[4], row[5], row[12]
                self.names[iso] = name
                self.capitals[iso] = capital
                first = re.sub(r"\D", "", re.split(r"\s+and\s+|,", phone)[0])
                if first:
                    first_code[iso] = first
                for code in re.split(r"\s+and\s+|,", phone):
                    digits = re.sub(r"\D", "", code)
                    if not digits:
                        continue
                    if digits in self.prefix_to_region:
                        continue
                    self.prefix_to_region.setdefault(digits, iso)
        # Shared codes belong to the main region only.
        shared = defaultdict(list)
        with open(os.path.join(raw, "countryInfo.txt"), encoding="utf-8") as f:
            for line in f:
                if line.startswith("#"):
                    continue
                row = line.rstrip("\n").split("\t")
                for code in re.split(r"\s+and\s+|,", row[12]):
                    digits = re.sub(r"\D", "", code)
                    if digits:
                        shared[digits].append(row[0])
        for digits, regions in shared.items():
            if len(regions) > 1:
                main = MAIN_REGION.get(digits)
                if main is None:
                    print(
                        f"warning: shared code +{digits} {regions} without a main region",
                        file=sys.stderr,
                    )
                    main = regions[0]
                self.prefix_to_region[digits] = main
        self.prefix_to_region.update(EXTRA_REGION_PREFIXES)
        for digits, iso in self.prefix_to_region.items():
            if iso not in self.region_prefix or len(digits) < len(self.region_prefix[iso]):
                self.region_prefix[iso] = digits
        # Regions inside a shared code without an own prefix (e.g. CA): a
        # country area without prefixes, for areas and mobile ranges.
        for iso, digits in first_code.items():
            self.region_prefix.setdefault(iso, digits)

    def region(self, digits):
        for n in range(len(digits), 0, -1):
            if digits[:n] in self.prefix_to_region:
                return self.prefix_to_region[digits[:n]]
        return None


def label_points(raw):
    """Natural Earth label point by ISO code, and the base map features."""
    reader = shapefile.Reader(os.path.join(raw, "ne50", "ne_50m_admin_0_countries"))
    fields = [f[0] for f in reader.fields[1:]]
    points = {}
    features = []
    for sr in reader.iterShapeRecords():
        rec = dict(zip(fields, sr.record))
        iso = rec["ISO_A2"] if rec["ISO_A2"] != "-99" else rec["ISO_A2_EH"]
        if iso and iso != "-99":
            points.setdefault(iso, (rec["LABEL_Y"], rec["LABEL_X"]))
        geom = shape(sr.shape.__geo_interface__).simplify(0.05, preserve_topology=True)
        if geom.is_empty:
            continue
        geo = mapping(geom)
        features.append(
            {
                "type": "Feature",
                "properties": {"iso": iso if iso != "-99" else ""},
                "geometry": round_coords(geo),
            }
        )
    return points, features


def round_coords(geo):
    def r(c):
        if isinstance(c, (list, tuple)) and c and isinstance(c[0], (int, float)):
            return [round(c[0], 2), round(c[1], 2)]
        return [r(x) for x in c]

    return {"type": geo["type"], "coordinates": r(geo["coordinates"])}


def countries(raw, regions, places, points):
    areas = []
    prefixes = []
    country_coords = {}
    for iso in sorted(regions.region_prefix):
        digits = regions.region_prefix[iso]
        coords = points.get(iso)
        if coords is None:
            coords = (
                places.find(iso, regions.capitals.get(iso, ""))
                if regions.capitals.get(iso)
                else None
            )
        if coords is None:
            print(f"warning: no coordinates for {iso}", file=sys.stderr)
            continue
        country_coords[iso] = coords
        cc = calling_code(digits)
        areas.append(
            (
                iso,
                iso,
                "country",
                coords[0],
                coords[1],
                display(cc, digits),
                regions.names.get(iso, iso),
            )
        )
        for p, region in sorted(regions.prefix_to_region.items()):
            if region == iso:
                prefixes.append((p, iso))
    return areas, prefixes, country_coords


CALLING_CODES = set()


def calling_code(digits):
    for n in (1, 2, 3):
        if digits[:n] in CALLING_CODES:
            return digits[:n]
    return digits[:1]


def germany(raw, today):
    names = {}
    names_dir = os.path.join(raw, "onb-names")
    csv_name = next(f for f in os.listdir(names_dir) if f.endswith(".csv"))
    with open(os.path.join(names_dir, csv_name), encoding="utf-8-sig") as f:
        for row in csv.DictReader(f, delimiter=";"):
            if (row.get("KennzeichenAktiv") or "1").strip() == "1" and row.get("Ortsnetzname"):
                names[row["Ortsnetzkennzahl"].strip()] = row["Ortsnetzname"].strip()
    shp_dir = os.path.join(raw, "onb")
    base = next(f[:-4] for f in os.listdir(shp_dir) if f.endswith(".shp"))
    reader = shapefile.Reader(os.path.join(shp_dir, base), encoding="utf-8")
    to_wgs84 = Transformer.from_crs("EPSG:31467", "EPSG:4326", always_xy=True).transform
    parts = defaultdict(list)
    for sr in reader.iterShapeRecords():
        geom = shape(sr.shape.__geo_interface__)
        if not geom.is_valid:
            geom = geom.buffer(0)
        parts[str(sr.record[0]).strip()].extend(getattr(geom, "geoms", [geom]))
    areas = {}
    for code, polygons in parts.items():
        # An area can have exclaves: use a point in its largest part.
        largest = max(polygons, key=lambda g: g.area)
        point = largest.representative_point()
        lon, lat = to_wgs84(point.x, point.y)
        areas[code] = (lat, lon)
    missing = sorted(set(areas) - set(names))
    if missing:
        print(f"warning: {len(missing)} ONB without a name: {missing[:10]}", file=sys.stderr)
    rows = []
    prefixes = []
    for code in sorted(areas, key=lambda c: (len(c), c)):
        lat, lon = areas[code]
        rows.append(
            (f"DE-{code}", "DE", "area", lat, lon, f"49 {code}", names.get(code, f"0{code}"))
        )
        prefixes.append((f"49{code}", f"DE-{code}"))
    write(
        os.path.join(OUT, "de.tsv"),
        {
            "title": "Germany, local network areas (Ortsnetzbereiche)",
            "source": "Bundesnetzagentur, ONB boundaries (GIS) and the area code list "
            "(Vorwahlverzeichnis); representative point inside each area",
            "license": "© Bundesnetzagentur. Free use, also in software and for third parties; "
            "keep the copyright notice",
            "updated": today,
        },
        rows,
        prefixes,
    )
    return len(rows)


def austria(raw, today):
    with open(os.path.join(raw, "rtr-ortsnetze.json"), encoding="utf-8") as f:
        data = json.load(f)["data"]
    towns = defaultdict(list)
    with open(os.path.join(raw, "at", "AT.txt"), encoding="utf-8") as f:
        for row in csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            if row[6] != "P":
                continue
            pop = int(row[14] or 0)
            rank = 0 if row[7] in ("PPLC", "PPLA", "PPLA2", "PPLA3") else 1
            place = (rank, -pop, float(row[4]), float(row[5]))
            names = {norm(row[1]), norm(row[2])}
            for n in names:
                towns[n].append(place)
            for alt in row[3].split(","):
                if norm(alt) and norm(alt) not in names:
                    towns[norm(alt)].append((rank + 2,) + place[1:])

    def variants(name):
        n = norm(name)
        yield n
        expanded = n
        for short, long in (
            (r"\ba d\b", "an der"),
            (r"\bi d\b", "in der"),
            (r"\ba\b", "am"),
            (r"\bi\b", "im"),
            (r"\bst\b", "sankt"),
            (r"\bb\b", "bei"),
            (r"\bo\b", "ob"),
        ):
            expanded = re.sub(short, long, expanded)
        yield expanded
        for sep in (" an der ", " am ", " im ", " in ", " bei ", " ob ", " ", "-"):
            if sep in expanded:
                yield expanded.split(sep)[0]
        yield expanded.replace("sankt", "st")

    rows, prefixes, unresolved = [], [], []
    for item in data:
        code = item["ortsnetzkennzahl"].strip()
        name = item["ortsnetzname"].strip()
        found = None
        for v in variants(name):
            if towns.get(v):
                best = min(towns[v])
                found = (best[2], best[3])
                break
        rows.append([f"AT-{code}", "AT", "area", found, f"43 {code}", name])
        prefixes.append((f"43{code}", f"AT-{code}"))
        if found is None:
            unresolved.append(code)
    # Areas without a match: the mean point of the resolved areas with the
    # same leading digits (Austrian area codes are grouped by region).
    for row in rows:
        if row[3] is not None:
            continue
        code = row[0][3:]
        for n in range(len(code) - 1, 0, -1):
            near = [r[3] for r in rows if r[3] is not None and r[0][3:].startswith(code[:n])]
            if near:
                row[3] = (sum(p[0] for p in near) / len(near), sum(p[1] for p in near) / len(near))
                break
    print(
        f"AT: {len(unresolved)} of {len(rows)} areas without a GeoNames place, "
        f"placed near their neighbours: {unresolved}",
        file=sys.stderr,
    )
    areas = [(r[0], r[1], r[2], r[3][0], r[3][1], r[4], r[5]) for r in rows]
    areas.sort(key=lambda a: (len(a[0]), a[0]))
    write(
        os.path.join(OUT, "at.tsv"),
        {
            "title": "Austria, local networks (Ortsnetze)",
            "source": "RTR Open Data, rnOrtsnetze (https://data.rtr.at/api/v1/tables/rnOrtsnetze.json); "
            "coordinates of the main place from GeoNames AT",
            "license": "RTR Open Data: free use, name the source (Source: RTR-GmbH, "
            "https://www.rtr.at/); GeoNames: CC BY 4.0 (https://www.geonames.org/)",
            "updated": today,
        },
        areas,
        prefixes,
    )
    return len(rows)


def mobile_prefixes(raw):
    carrier_dir = os.path.join(raw, "libphonenumber", "resources", "carrier", "en")
    out = set()
    for file in os.listdir(carrier_dir):
        if file.endswith(".txt"):
            out.update(p for p, _ in read_lpn(os.path.join(carrier_dir, file)))
    return out


def overlaps(prefix, ranges):
    """True if `prefix` is inside one of `ranges` or contains one."""
    if any(prefix[:n] in ranges for n in range(1, len(prefix) + 1)):
        return True
    return False


def world(raw, regions, places, today):
    lpn = os.path.join(raw, "libphonenumber")
    tag = open(os.path.join(lpn, "TAG"), encoding="utf-8").read().strip()
    geo_dir = os.path.join(lpn, "resources", "geocoding", "en")
    area_ids = {}
    areas = []
    mapping_by_prefix = {}
    total = resolved = 0
    # The geocoding data of mobile ranges is the home region of the number,
    # not the location of the caller. Such numbers count as mobile.
    mobile_ranges = mobile_prefixes(raw)
    for file in sorted(os.listdir(geo_dir), key=lambda f: int(f.split(".")[0])):
        cc = file.split(".")[0]
        if cc in OWN_DATA:
            continue
        for prefix, text in read_lpn(os.path.join(geo_dir, file)):
            total += 1
            if overlaps(prefix, mobile_ranges) or prefix in regions.prefix_to_region:
                continue
            region = regions.region(prefix)
            if region is None:
                continue
            if cc == "1":
                tail = text.rsplit(", ", 1)[-1] if ", " in text else None
                if tail in CA_PROVINCES or text in CA_PROVINCES.values():
                    region = "CA"
            if norm(text) == norm(regions.names.get(region, "")):
                continue
            coords = None
            for name, admin1 in lpn_place_names(text):
                a1 = admin1 if region == "US" else None
                coords = places.find(region, name, a1)
                if coords:
                    break
            if coords is None:
                continue
            resolved += 1
            key = (region, text)
            if key not in area_ids:
                area_ids[key] = None
                areas.append([key, coords, cc])
            mapping_by_prefix[prefix] = key
    kept = compact(mapping_by_prefix, set(regions.prefix_to_region))
    members_of = defaultdict(list)
    for p, k in kept.items():
        members_of[k].append(p)
    out_areas = []
    counter = defaultdict(int)
    for key, coords, cc in areas:
        if key not in members_of:
            continue
        region, text = key
        members = members_of[key]
        lcp = common_prefix(members)
        shown = lcp if len(lcp) > len(cc) else min(members, key=len)
        base_id = f"{region}-{shown[len(cc) :] or '0'}"
        counter[base_id] += 1
        area_id = base_id if counter[base_id] == 1 else f"{base_id}-{counter[base_id]}"
        area_ids[key] = area_id
        out_areas.append((area_id, region, "area", coords[0], coords[1], display(cc, shown), text))
    prefixes = sorted(((p, area_ids[k]) for p, k in kept.items()), key=lambda x: x[0])
    print(
        f"world: {resolved} of {total} geocoding prefixes are fixed-line prefixes with coordinates",
        file=sys.stderr,
    )
    write(
        os.path.join(OUT, "world.tsv"),
        {
            "title": "Other countries, places by number prefix",
            "source": f"libphonenumber {tag} resources/geocoding/en (without +41, +43, +49); "
            "coordinates from GeoNames cities15000",
            "license": "libphonenumber: Apache License 2.0 (https://github.com/google/libphonenumber); "
            "GeoNames: CC BY 4.0 (https://www.geonames.org/)",
            "updated": today,
        },
        out_areas,
        prefixes,
    )


def mobile(raw, regions, today, country_coords, geographic):
    lpn = os.path.join(raw, "libphonenumber")
    tag = open(os.path.join(lpn, "TAG"), encoding="utf-8").read().strip()
    carrier_dir = os.path.join(lpn, "resources", "carrier", "en")
    mapping_by_prefix = {}
    conflicts = 0
    for file in sorted(os.listdir(carrier_dir)):
        if not file.endswith(".txt"):
            continue
        for prefix, _ in read_lpn(os.path.join(carrier_dir, file)):
            region = regions.region(prefix)
            if region is None or region not in country_coords or prefix in regions.prefix_to_region:
                continue
            if any(
                prefix.startswith(g) or g.startswith(prefix) for g in geographic.get(prefix[:3], ())
            ):
                conflicts += 1
                continue
            mapping_by_prefix[prefix] = f"{region}-mobile"
    taken = set(regions.prefix_to_region) | file_prefixes("world.tsv")
    for group in geographic.values():
        taken |= group
    kept = compact(mapping_by_prefix, taken)
    used = sorted(set(kept.values()))
    areas = []
    for area_id in used:
        iso = area_id.split("-")[0]
        lat, lon = country_coords[iso]
        digits = regions.region_prefix[iso]
        areas.append(
            (
                area_id,
                iso,
                "mobile",
                lat,
                lon,
                display(calling_code(digits), digits),
                regions.names.get(iso, iso),
            )
        )
    print(
        f"mobile: {conflicts} carrier prefixes overlap area codes and are left out", file=sys.stderr
    )
    write(
        os.path.join(OUT, "mobile.tsv"),
        {
            "title": "Mobile number ranges of all countries",
            "source": f"libphonenumber {tag} resources/carrier/en (prefixes only, without carrier names)",
            "license": "Apache License 2.0 (https://github.com/google/libphonenumber)",
            "updated": today,
        },
        areas,
        sorted(kept.items()),
    )


def geographic_prefixes():
    """Prefixes of the area files, grouped by their first three digits."""
    out = defaultdict(set)
    for name in ("de.tsv", "at.tsv", "ch.tsv", "service.tsv"):
        for digits in file_prefixes(name):
            out[digits[:3]].add(digits)
    return out


def file_prefixes(name):
    with open(os.path.join(OUT, name), encoding="utf-8") as f:
        return {line.split("\t")[1] for line in f if line.startswith("P\t")}


